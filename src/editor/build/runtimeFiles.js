/**
 * Which files of the prebuilt player template a game actually needs.
 *
 * The runtime is one Vite build (`vite.player.config.js`) whose heavy parts —
 * Rapier, the GI system, Recast, the Draco and Basis decoders, every
 * post-processing addon, the script-runtime proxies — are code-split behind
 * dynamic imports. The exporter used to copy the whole `dist-player/` folder
 * regardless, so a game with no physics shipped 2.2 MB of Rapier, a game with
 * no GI shipped the GI system and its workers, and every game shipped the
 * editor's public-folder leftovers (`tauri.svg`, `app-icon.png`).
 *
 * This walks the Vite manifest (`.vite/manifest.json`, one entry per chunk with
 * its static `imports`, its `dynamicImports` and the `assets` it references)
 * from the entry chunk. Static imports are always followed; a dynamic import is
 * followed only when the feature that issues it is in the build: the module is
 * enabled in the project, an asset of the format the loader decodes ships, a
 * shipped script imports the proxied specifier. Files the manifest does not
 * know about (Web Workers, the `public/` folder) are decided by name.
 *
 * Every rule errs towards shipping: an unrecognised dynamic import, an unknown
 * worker chunk or an unknown loose file is copied. Trimming saves bytes; a
 * missing chunk is a game that fails to load a level.
 *
 * Pure on purpose — `npm run test:build` drives it in Node.
 */

/** Manifest keys (source paths) under a module's folder belong to that module. */
const moduleDirOf = (key) => /^src\/modules\/([^/]+)\//.exec(key)?.[1] ?? null;

/**
 * Whether the chunk behind a dynamic import can be reached by this game.
 * `key` is the manifest key — the SOURCE path of the imported module — so the
 * rules read like the import sites they mirror (see the survey of `import(`
 * calls in src/engine and src/modules).
 */
function reachable(key, ctx) {
  const dir = moduleDirOf(key);
  if (dir) return ctx.module(dir);
  // Module-owned third-party code (the import site lives in the module's shell,
  // which the entry chunk statically includes, so the manifest attributes the
  // dynamic import to the entry rather than to the module).
  if (key.startsWith("node_modules/@dimforge/rapier")) return ctx.module("physics-rapier");
  if (key.startsWith("node_modules/recast-navigation/") || key.startsWith("node_modules/@recast-navigation/")) {
    return ctx.module("navigation");
  }
  if (key.startsWith("node_modules/meshoptimizer/")) return ctx.module("gi") || ctx.module("virtual-geometry");
  if (key.includes("/jsm/tsl/display/")) return ctx.module("postprocessing");
  if (key.startsWith("node_modules/@tauri-apps/")) return ctx.module("ambientcg");
  // Format loaders in the engine core: needed exactly when such a file ships.
  if (key.endsWith("/loaders/EXRLoader.js")) return ctx.ext("exr");
  if (key.endsWith("/loaders/HDRLoader.js") || key.endsWith("/loaders/RGBELoader.js")) return ctx.ext("hdr");
  if (key.endsWith("/loaders/KTX2Loader.js")) return ctx.basis;
  // Script-runtime proxies: a shipped script imports the bare specifier, the
  // player links it to the proxy chunk (`linkEngineImports`).
  if (key === "src/engine/scriptRuntime/runtime.js") return true;
  if (key === "src/engine/scriptRuntime/editorRuntime.js") return ctx.imports("editor");
  if (key === "src/engine/scriptRuntime/threeRuntime.js") return ctx.imports("three") || ctx.imports("three/webgpu");
  if (key === "src/engine/scriptRuntime/tslRuntime.js") return ctx.imports("three/tsl");
  if (key === "src/engine/scriptRuntime/orbitControlsRuntime.js") {
    return ctx.imports("three/addons/controls/OrbitControls.js");
  }
  if (key === "src/player/liveUpdate.js") return ctx.livePreview;
  return true;
}

/**
 * Files the manifest cannot attribute — Web Workers (Vite emits them as
 * chunks but does not list them), the `public/` folder copied verbatim, and
 * decoder binaries referenced by URL. Matched on the template-relative path;
 * the first matching rule decides. A worker added to a module later must be
 * added here too, or it ships with every game (safe, just not trimmed).
 */
const LOOSE_FILE_RULES = [
  // Bookkeeping and the editor's own public-folder leftovers.
  [/^\.vite\//, () => false],
  [/^index\.html$/, () => false], // regenerated by the exporter
  [/^(app-icon\.png|tauri\.svg)$/, () => false],
  // The study's public files are developer fixtures. Production World surfaces
  // are module-owned Vite assets and arrive through its manifest closure.
  [/^world-study\//, () => false],
  // Workers.
  [/^_engine\/bvhBlasWorker-/, (ctx) => ctx.module("gi")],
  [/^_engine\/staticBvhVerifyWorker-/, (ctx) => ctx.module("gi")],
  [/^_engine\/cloudNoiseWorker-/, (ctx) => ctx.module("postprocessing")],
  [/^_engine\/worldPlan\.worker-/, (ctx) => ctx.module("world")],
  // Decoder binaries: the hashed copies the bundle references and the plain
  // `public/` copies the loaders are pointed at (`setDecoderPath("draco/")`).
  [/^(_engine\/draco_|draco\/)/, (ctx) => ctx.draco],
  [/^(_engine\/basis_transcoder|basis\/)/, (ctx) => ctx.basis],
];

const looseRule = (rel) => LOOSE_FILE_RULES.find(([pattern]) => pattern.test(rel))?.[1] ?? null;

/**
 * The bare specifiers shipped scripts import — `"three"`, `"three/tsl"`,
 * `"editor"` — found by shape in transpiled source. A false positive costs one
 * 20 KB proxy chunk; a false negative is a script that fails to link.
 */
export function scriptImportSpecifiers(sources) {
  const found = new Set();
  const re = /(?:from|import)\s*\(?\s*(['"])([^'"\n]+)\1/g;
  for (const code of sources) {
    if (typeof code !== "string") continue;
    for (const match of code.matchAll(re)) found.add(match[2]);
  }
  return found;
}

/**
 * @param {object} args
 * @param {Record<string, any> | null} args.manifest  parsed `.vite/manifest.json`
 * @param {Array<string | [string, number]>} args.templateFiles  every file in the
 *   template, template-relative, optionally with its size
 * @param {string[]} args.modules  the module ids the build enables (`scene.modules`)
 * @param {Iterable<string>} [args.assetExtensions]  lower-case extensions of every
 *   shipped file
 * @param {Iterable<string>} [args.scriptImports]  bare specifiers shipped scripts import
 * @param {boolean} [args.livePreview]
 * @param {boolean} [args.compressTextures]  Basis derivatives are written at build time
 * @param {boolean} [args.compressModels]  Draco-compressed .glb are written at build time
 * @param {boolean} [args.dracoModels]  a shipped .glb already uses KHR_draco_mesh_compression
 * @returns {{ files: string[], skipped: Array<{ rel: string, size: number }>,
 *   shippedBytes: number, skippedBytes: number, trimmed: boolean }}
 *   `trimmed` is false when there was no manifest to walk — everything ships.
 */
export function selectRuntimeFiles({
  manifest,
  templateFiles,
  modules = [],
  assetExtensions = [],
  scriptImports = [],
  livePreview = false,
  compressTextures = false,
  compressModels = false,
  dracoModels = false,
}) {
  const enabled = new Set(modules);
  const exts = new Set([...assetExtensions].map((e) => String(e).toLowerCase()));
  const imports = new Set(scriptImports);
  const ctx = {
    module: (id) => enabled.has(id),
    ext: (e) => exts.has(e),
    imports: (spec) => imports.has(spec),
    livePreview: !!livePreview,
    // The engine core wires the Draco decoder into every glTF load and only
    // fetches it for a compressed mesh, so the module is not the only reason
    // a game needs it: a downloaded model may arrive compressed.
    draco: enabled.has("draco") || !!compressModels || !!dracoModels,
    basis: enabled.has("basis") || !!compressTextures || exts.has("basis") || exts.has("ktx2"),
  };

  const sizes = new Map();
  for (const entry of templateFiles ?? []) {
    if (Array.isArray(entry)) sizes.set(entry[0], Number(entry[1]) || 0);
    else sizes.set(String(entry), 0);
  }

  const entryKey = manifest && typeof manifest === "object"
    ? Object.keys(manifest).find((k) => manifest[k]?.isEntry)
    : null;

  // Everything the manifest knows about, and the subset this game reaches.
  const known = new Set();
  const reached = new Set();
  if (entryKey) {
    for (const chunk of Object.values(manifest)) {
      if (chunk?.file) known.add(chunk.file);
      for (const f of chunk?.css ?? []) known.add(f);
      for (const f of chunk?.assets ?? []) known.add(f);
    }
    const visited = new Set();
    const visit = (key) => {
      if (visited.has(key)) return;
      visited.add(key);
      const chunk = manifest[key];
      if (!chunk) return;
      if (chunk.file) reached.add(chunk.file);
      for (const f of chunk.css ?? []) reached.add(f);
      for (const f of chunk.assets ?? []) reached.add(f);
      for (const dep of chunk.imports ?? []) visit(dep);
      for (const dep of chunk.dynamicImports ?? []) if (reachable(dep, ctx)) visit(dep);
    };
    visit(entryKey);
  }

  const files = [];
  const skipped = [];
  let shippedBytes = 0;
  let skippedBytes = 0;
  for (const [rel, size] of sizes) {
    const rule = looseRule(rel);
    let ship;
    if (rule) ship = rule(ctx);
    else if (entryKey && known.has(rel)) ship = reached.has(rel);
    else ship = true;
    if (ship) {
      files.push(rel);
      shippedBytes += size;
    } else {
      skipped.push({ rel, size });
      skippedBytes += size;
    }
  }
  return { files, skipped, shippedBytes, skippedBytes, trimmed: !!entryKey };
}
